.data
A:
# 3×3 matrix A (row-major)
    .word 0x40a00000   # 5.0
    .word 0x40000000   # 2.0
    .word 0x3f800000   # 1.0

    .word 0x40000000   # 2.0
    .word 0x40400000   # 3.0
    .word 0x00000000   # 0.0

    .word 0x3f800000   # 1.0
    .word 0x00000000   # 0.0
    .word 0x40800000   # 4.0

.text
############################################################
# Load matrix A into FP registers f0..f8
############################################################
    la t0, A
    # li t0, 0x100
    # data segment starts at 0x100

    flw f0,  0(t0)   # A00
    flw f1,  4(t0)   # A01
    flw f2,  8(t0)   # A02
    flw f3, 12(t0)   # A10
    flw f4, 16(t0)   # A11
    flw f5, 20(t0)   # A12
    flw f6, 24(t0)   # A20
    flw f7, 28(t0)   # A21
    flw f8, 32(t0)   # A22

############################################################
# U00 U01 U02
############################################################
    fsgnj.s f20, f0, f0    # U00
    fsgnj.s f21, f1, f1    # U01
    fsgnj.s f22, f2, f2    # U02

############################################################
# L10 = A10/U00     L20 = A20/U00
############################################################
    fdiv.s f10, f3, f20    # L10
    fdiv.s f11, f6, f20    # L20

############################################################
# U11 = A11 - L10 * U01
############################################################
    fmul.s f12, f10, f21
    fsub.s f23, f4, f12    # U11

############################################################
# U12 = A12 - L10 * U02
############################################################
    fmul.s f13, f10, f22
    fsub.s f24, f5, f13    # U12

############################################################
# L21 = (A21 - L20*U01) / U11
############################################################
    fmul.s f14, f11, f21
    fsub.s f15, f7, f14
    fdiv.s f16, f15, f23   # L21/d

############################################################
# U22 = A22 - L20*U02 - L21*U12
############################################################
    fmul.s f17, f11, f22
    fmul.s f18, f16, f24
    fadd.s f19, f17, f18
    fsub.s f25, f8, f19   # U22

############################################################
# STORE RESULT TO ABSOLUTE ADDRESS 0x00000000
#
# ORDER:
#   L00 L01 L02
#   L10 L11 L12
#   L20 L21 L22
#   0x00000000
#   0x00000000
#   U00 U01 U02
#   U10 U11 U12
#   U20 U21 U22
############################################################

    li t2, 0 # base address

    # 1. L00 L01 L02
    li t0, 1
    fcvt.s.w f30, t0
    fsw f30, 0(t2)         # L00 = 1.0
    sw  x0,  4(t2)         # L01 = 0
    sw  x0,  8(t2)         # L02 = 0

    # 2. L10 L11 L12
    fsw f10, 12(t2)        # L10
    fsw f30, 16(t2)        # L11 = 1.0
    sw  x0,  20(t2)        # L12 = 0

    # 3. L20 L21 L22
    fsw f11, 24(t2)        # L20
    fsw f16, 28(t2)        # L21
    fsw f30, 32(t2)        # L22 = 1.0

    # 4. Two zero words
    sw  x0, 36(t2)
    sw  x0, 40(t2)

    # 5. U00 U01 U02
    fsw f20, 44(t2)
    fsw f21, 48(t2)
    fsw f22, 52(t2)

    # 6. U10 U11 U12
    sw  x0,  56(t2)        # U10 = 0
    fsw f23, 60(t2)
    fsw f24, 64(t2)

    # 7. U20 U21 U22
    sw  x0,  68(t2)        # U20 = 0
    sw  x0,  72(t2)        # U21 = 0
    fsw f25, 76(t2)

############################################################
# DONE: halt
############################################################
halt:
    jal x0, halt